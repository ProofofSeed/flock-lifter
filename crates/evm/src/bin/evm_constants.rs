//! Writes `verifier/src/Constants.sol`: every value the contract takes from Flock or from the
//! lifter's statement rather than computing it — the φ₈ nodes and their denominators, the fixed
//! zerocheck challenges, the chunk statement digests, the transcript labels and the Ligerito
//! schedule of every chunk size.

use std::fmt::Write;

use flock_prover::{
    field::F128,
    pcs::ligerito::eval_sk_at_vks,
    zerocheck::{
        multilinear::subspace_denominator_pair,
        univariate_skip_optimized::{medium_challenges_ghash, small_challenges_ghash},
    },
};
use flock_prover::field::PHI_8_TABLE;
use pofseed_flock_lift::chunk_rm::{pcs_params, statement_digest};
use pofseed_flock_lift_block::{
    keccak::{N_ROUNDS, ROUND_CONSTANTS, STATE_BITS, state_idx, theta_rho_pi_preimage},
    program::Program,
};
use pofseed_flock_lift_evm::{calldata::M_RANGE, evm::project};
use pofseed_flock_lift_host::{HARDENED_OFFSET, bip32_vector_1};
use pofseed_flock_lift_statement::HardenedChildCircuit;

/// `RHO_OFFSETS[a][b] mod 64`, recovered from the preimage map: the preimage of `(x, y, 0)` with
/// `a = (x + 3y) mod 5`, `b = x` starts at `(a, b, (64 − r) mod 64)`.
fn rho_offset(a: usize, b: usize) -> u32 {
    for x in 0..5 {
        for y in 0..5 {
            if (x + 3 * y) % 5 == a && x == b {
                let first = theta_rho_pi_preimage(x, y, 0)[0];
                let c = first / 25;
                return ((64 - c) % 64) as u32;
            }
        }
    }
    unreachable!("every (a, b) has a preimage position");
}

fn hex(v: F128) -> String {
    return format!("0x{:032x}", ((v.hi as u128) << 64) | v.lo as u128);
}

/// A label as absorbed: header then padded bytes, as whole words, with its byte length.
fn label(name: &str, bytes: &[u8]) -> String {
    let mut buf = vec![0x02u8, 0];
    buf.extend_from_slice(&[0u8; 6]);
    buf.extend_from_slice(&(bytes.len() as u64).to_be_bytes());
    buf.extend_from_slice(bytes);
    buf.resize(buf.len().div_ceil(16) * 16, 0);
    let len = buf.len();
    buf.resize(buf.len().div_ceil(32) * 32, 0);
    assert!(buf.len() <= 64, "labels fit two words");
    buf.resize(64, 0);
    return format!(
        "    uint256 internal constant {name}_0 = 0x{};\n    uint256 internal constant {name}_1 = 0x{};\n    uint256 internal constant {name}_LEN = {len};\n",
        hex::encode(&buf[..32]),
        hex::encode(&buf[32..])
    );
}

fn list(v: &[usize]) -> String {
    return v.iter().map(|x| x.to_string()).collect::<Vec<_>>().join(", ");
}

fn main() {
    let mut s = String::new();
    s.push_str("// SPDX-License-Identifier: LGPL-3.0-or-later\npragma solidity ^0.8.30;\n\n");
    s.push_str("// Generated by `cargo run --release -p pofseed-flock-lift-evm --bin evm-constants`; do not edit.\n\n");
    s.push_str("/// The Ligerito schedule of one chunk size.\nstruct LigeritoConfig {\n    uint256 steps;\n    uint256 initialK;\n    uint256[] logInvRates;\n    uint256[] recursiveKs;\n    uint256[] queries;\n    uint256[] grindingBits;\n    uint256[] claimBits;\n    uint256[] consistencyBits;\n    uint256[] oodSamples;\n    uint256[] logBlockLens;\n    uint256[][] depths;\n}\n\n");
    s.push_str("/// Constants the verifier takes from Flock and from the lifted statement.\nlibrary Constants {\n");
    writeln!(s, "    uint256 internal constant DEN6_INV = {};", hex(subspace_denominator_pair(6).1)).unwrap();
    writeln!(s, "    uint256 internal constant DEN7_INV = {};", hex(subspace_denominator_pair(7).1)).unwrap();
    for (i, v) in small_challenges_ghash().iter().chain(medium_challenges_ghash().iter()).enumerate() {
        writeln!(s, "    uint256 internal constant FIXED_R_{i} = {};", hex(*v)).unwrap();
    }
    let sks = eval_sk_at_vks(24);
    let packed = |v: &mut dyn Iterator<Item = F128>| -> String { v.map(|x| hex(x)[2..].to_string()).collect() };
    writeln!(s, "    /// The φ₈ nodes `x^0 … x^127` images, sixteen bytes each.").unwrap();
    writeln!(s, "    bytes internal constant PHI8 = hex\"{}\";", packed(&mut PHI_8_TABLE[..128].iter().copied())).unwrap();
    writeln!(s, "    /// `s_k(v_k)` for k in 0..=24, sixteen bytes each.").unwrap();
    writeln!(s, "    bytes internal constant SKS = hex\"{}\";", packed(&mut sks.iter().copied())).unwrap();
    writeln!(s, "    /// The inverses of `s_k(v_k)`, zero for zero, sixteen bytes each.").unwrap();
    writeln!(s, "    bytes internal constant SKS_INV = hex\"{}\";", packed(&mut sks.iter().map(|v| if v.is_zero() { F128::ZERO } else { v.inv() }))).unwrap();
    let spread: String = (0..256u32)
        .map(|b| {
            let mut v = [0u8; 32];
            for t in 0..8 {
                if (b >> t) & 1 == 1 {
                    v[31 - 4 * t] = 1;
                }
            }
            hex::encode(v)
        })
        .collect();
    writeln!(s, "    /// Byte `b` spread to one bit per 32-bit slot: bit `t` of `b` at bit `32·t`.").unwrap();
    writeln!(s, "    bytes internal constant SPREAD8 = hex\"{spread}\";").unwrap();
    let mut rc = [false; STATE_BITS];
    let mut masks = Vec::new();
    for r in 0..=N_ROUNDS {
        let lanes: Vec<u64> = (0..25)
            .map(|l| (0..64).filter(|&z| rc[state_idx(l % 5, l / 5, z)]).fold(0u64, |m, z| m | (1 << z)))
            .collect();
        masks.push(lanes);
        if r == N_ROUNDS {
            break;
        }
        let mut next = [false; STATE_BITS];
        for s_out in 0..STATE_BITS {
            let pre = theta_rho_pi_preimage(s_out % 25 % 5, (s_out % 25) / 5, s_out / 25);
            next[s_out] = pre.iter().fold(false, |acc, &p| acc ^ rc[p]);
        }
        for z in 0..64 {
            if (ROUND_CONSTANTS[r] >> z) & 1 == 1 {
                next[state_idx(0, 0, z)] ^= true;
            }
        }
        rc = next;
    }
    let rc_hex: String = masks.iter().flatten().map(|m| format!("{m:016x}")).collect();
    writeln!(s, "    /// The round-constant state before round r of Keccak-f (r = 24 after the last), 25 eight-byte lane masks per round.").unwrap();
    writeln!(s, "    bytes internal constant RC_MASKS = hex\"{rc_hex}\";").unwrap();
    let mut rho = String::new();
    let offsets: Vec<u32> = (0..25).map(|i| rho_offset(i / 5, i % 5)).collect();
    for o in &offsets {
        rho.push_str(&format!("{o:02x}"));
    }
    writeln!(s, "    /// Keccak's ρ offsets modulo 64, `RHO[5·a + b]`.").unwrap();
    writeln!(s, "    bytes internal constant RHO = hex\"{rho}\";").unwrap();
    let (_, chain_code) = bip32_vector_1();
    let program = Program::new(&HardenedChildCircuit::public_only(chain_code, HARDENED_OFFSET));
    for m in M_RANGE {
        writeln!(s, "    bytes32 internal constant STATEMENT_DIGEST_{m} = 0x{};", hex::encode(statement_digest(&program, m - 28))).unwrap();
    }
    for (name, bytes) in [
        ("L_WORDS", &b"pofseed-flock-lift-published-words"[..]),
        ("L_R1CS", b"flock-r1cs-v0"),
        ("L_ZEROCHECK", b"flock-zerocheck-v0"),
        ("L_LINCHECK", b"flock-lincheck-v0"),
        ("L_OPEN", b"flock-pcs-open-batch-v0"),
        ("L_RING", b"flock-ring-switch-v0"),
        ("L_LIGERITO", b"flock-ligerito-basis-f256-split-v0"),
    ] {
        s.push_str(&label(name, bytes));
    }
    s.push_str("\n    /// Entry `i` of a table of sixteen-byte big-endian values.\n    function at(bytes memory table, uint256 i) internal pure returns (uint256 v) {\n        assembly (\"memory-safe\") {\n            v := shr(128, mload(add(add(table, 32), mul(i, 16))))\n        }\n    }\n\n");
    s.push_str("    /// The Ligerito schedule of a chunk committing `2^m` bits.\n    function ligerito(uint256 m) internal pure returns (LigeritoConfig memory c) {\n");
    for m in M_RANGE {
        let cfg = pcs_params(m).ligerito_verifier_config().expect("registered configuration");
        writeln!(s, "        if (m == {m}) {{").unwrap();
        writeln!(s, "            c.steps = {};", cfg.recursive_steps).unwrap();
        writeln!(s, "            c.initialK = {};", cfg.initial_k).unwrap();
        for (field, v) in [
            ("logInvRates", &cfg.log_inv_rates),
            ("recursiveKs", &cfg.recursive_ks),
            ("queries", &cfg.queries),
            ("grindingBits", &cfg.grinding_bits),
            ("claimBits", &cfg.claim_batch_grinding_bits),
            ("consistencyBits", &cfg.consistency_batch_grinding_bits),
            ("oodSamples", &cfg.ood_samples),
        ] {
            writeln!(s, "            c.{field} = new uint256[]({});", v.len()).unwrap();
            for (i, x) in v.iter().enumerate() {
                writeln!(s, "            c.{field}[{i}] = {x};").unwrap();
            }
        }
        assert!(cfg.fold_grinding_bits.iter().all(|&b| b == 0));
        let n = cfg.stratified.len();
        writeln!(s, "            c.logBlockLens = new uint256[]({n});").unwrap();
        writeln!(s, "            c.depths = new uint256[][]({n});").unwrap();
        for (i, l) in cfg.stratified.iter().enumerate() {
            writeln!(s, "            c.logBlockLens[{i}] = {};", l.log_block_len).unwrap();
            writeln!(s, "            c.depths[{i}] = new uint256[]({});", l.summand_depths.len()).unwrap();
            for (j, d) in l.summand_depths.iter().enumerate() {
                writeln!(s, "            c.depths[{i}][{j}] = {d};").unwrap();
            }
            let _ = list(&l.summand_depths);
        }
        s.push_str("            return c;\n        }\n");
    }
    s.push_str("        revert(\"unsupported chunk size\");\n    }\n}\n");
    let path = project().join("src/Constants.sol");
    std::fs::write(&path, s).expect("write constants");
    println!("wrote {}", path.display());
}
