//! The Solidity source of a wrapped lift's constants: `verifier/src/wrap/WrapKey.sol`.

use std::fmt::Write;

use flock_prover::field::F128;
use pofseed_flock_lift::wrap::WRAP_DOMAIN;
use pofseed_flock_lift_structure::{key::Held, subfield::dual};
use pofseed_flock_lift_whir::{domain::Domain, merkle::cap_size, params::Config};

use crate::wrap::{
    opening::frobenius_constants,
    vk::{Sparse, Vk},
};

fn f128(v: F128) -> [u8; 16] {
    return (((v.hi as u128) << 64) | v.lo as u128).to_be_bytes();
}

/// A transcript operation: its header, then its payload padded to a multiple of sixteen bytes.
fn op(code: u8, kind: u8, len: u64, payload: &[u8]) -> Vec<u8> {
    let mut out = vec![code, kind, 0, 0, 0, 0, 0, 0];
    out.extend_from_slice(&len.to_be_bytes());
    out.extend_from_slice(payload);
    out.resize(out.len().div_ceil(16) * 16, 0);
    return out;
}

fn label(bytes: &[u8]) -> Vec<u8> {
    return op(2, 0, bytes.len() as u64, bytes);
}

fn bytes_op(bytes: &[u8]) -> Vec<u8> {
    return op(5, 0, bytes.len() as u64, bytes);
}

/// A label as absorbed, as two words and its length in the transcript.
fn label_words(s: &mut String, name: &str, bytes: &[u8]) {
    let mut buf = label(bytes);
    let len = buf.len();
    assert!(len <= 64, "labels fit two words");
    buf.resize(64, 0);
    writeln!(
        s,
        "    uint256 internal constant {name}_0 = 0x{};\n    uint256 internal constant {name}_1 = 0x{};\n    uint256 internal constant {name}_LEN = {len};",
        hex::encode(&buf[..32]),
        hex::encode(&buf[32..])
    )
    .unwrap();
}

fn constant(s: &mut String, doc: &str, name: &str, value: usize) {
    writeln!(s, "    /// {doc}\n    uint256 internal constant {name} = {value};").unwrap();
}

fn blob(s: &mut String, doc: &str, name: &str, bytes: &[u8]) {
    writeln!(s, "    /// {doc}\n    bytes internal constant {name} = hex\"{}\";", hex::encode(bytes)).unwrap();
}

/// A sparse matrix by rows: its nonempty rows' number, then per row its index, its entries' number,
/// and per entry its column, whether a coefficient follows, and the coefficient if it is not one.
fn sparse(m: &Sparse) -> Vec<u8> {
    let rows: Vec<(usize, &Vec<(usize, F128)>)> = m.iter().enumerate().filter(|(_, r)| !r.is_empty()).collect();
    let mut out = (rows.len() as u16).to_be_bytes().to_vec();
    for (r, entries) in rows {
        out.push(r as u8);
        out.push(entries.len() as u8);
        for &(c, v) in entries {
            out.push(c as u8);
            if v == F128::ONE {
                out.push(0);
            } else {
                out.push(1);
                out.extend_from_slice(&f128(v));
            }
        }
    }
    return out;
}

/// A sparse vector: its nonzeros' number, then per nonzero its index and its value.
fn sparse_vector(v: &[F128]) -> Vec<u8> {
    let nonzero: Vec<(usize, F128)> = v.iter().copied().enumerate().filter(|(_, x)| !x.is_zero()).collect();
    let mut out = (nonzero.len() as u16).to_be_bytes().to_vec();
    for (i, x) in nonzero {
        out.push(i as u8);
        out.extend_from_slice(&f128(x));
    }
    return out;
}

/// A WHIR schedule: per committed function its variables, folded variables, log domain size,
/// queries (two bytes), out-of-domain samples and log cap size; and the final variables.
fn schedule(config: &Config) -> (Vec<u8>, usize) {
    let schedule = config.schedule().expect("a secure configuration");
    let mut out = Vec::new();
    for r in &schedule.rounds {
        let cap = cap_size(1 << r.log_domain, r.queries).trailing_zeros() as u8;
        out.extend_from_slice(&[r.vars as u8, r.fold as u8, r.log_domain as u8, (r.queries >> 8) as u8, r.queries as u8, r.ood as u8, cap]);
    }
    return (out, schedule.final_vars);
}

/// The source of the library holding the constants of `vk`.
pub fn key_source(vk: &Vk) -> String {
    let mut s = String::new();
    s.push_str("// SPDX-License-Identifier: LGPL-3.0-or-later\npragma solidity ^0.8.30;\n\n");
    s.push_str("// Generated by `cargo run --release -p pofseed-flock-lift-evm --bin wrap-bench`; do not edit.\n\n");
    s.push_str("/// The constants of one wrapped lift's verifier: the wrap circuit's shape, its commitment's\n/// schedule, and the commitment to one statement's fixed tables.\nlibrary WrapKey {\n");
    constant(&mut s, "log2 of the circuit's rows.", "NU", vk.nu);
    constant(&mut s, "Variables of the Boolean region.", "M_BOOL", vk.m_bool);
    constant(&mut s, "Variables of the element region.", "M_ELEM", vk.m_elem);
    constant(&mut s, "log2 of the committed stack's words.", "DENSE_LOG", vk.dense_log);
    constant(&mut s, "log2 of the cells.", "MU", vk.mu);
    constant(&mut s, "Proof-of-work bits before the wiring argument's fingerprint challenge.", "GKR_BITS", vk.gkr_bits as usize);
    constant(&mut s, "Gate cell slots.", "N_GATE", vk.gate_cols.len());
    constant(&mut s, "Words of the public segment.", "NUM_PUBLIC", vk.num_public);
    constant(&mut s, "Fixed words opening the public segment.", "N_FIXED", vk.fixed.len());
    constant(&mut s, "Boolean table types.", "N_BOOL", vk.bools.len());
    constant(&mut s, "Element table types.", "N_ELEM", vk.elems.len());
    constant(&mut s, "Committed tables.", "N_TABLES", vk.n_tables);
    constant(&mut s, "Frozen high coordinates of the element region, as a bit pattern.", "ELEM_FROZEN", vk.elem_frozen.iter().enumerate().fold(0, |acc, (i, &b)| acc | (b as usize) << i));
    constant(&mut s, "Responses per lift.", "RESPONSES", vk.responses);
    constant(&mut s, "Responses per chunk.", "CHUNK", vk.chunk);
    constant(&mut s, "Published words per response.", "N_IO", vk.n_io);
    constant(&mut s, "The expected output's word counts: 8-bit words, then 32-bit words shifted by 16, then 64-bit words shifted by 32.", "COUNTS", vk.counts as usize);

    let mut prefix = op(1, 0, WRAP_DOMAIN.len() as u64, WRAP_DOMAIN);
    prefix.extend(label(b"pofseed-flock-lift-wrap-public"));
    prefix.extend(op(3, 2, vk.num_public as u64, &[]));
    blob(&mut s, "The outer transcript before the public words: the domain, the label and the slice header.", "BIND_PREFIX", &prefix);
    blob(&mut s, "The fixed public words, sixteen bytes each.", "FIXED", &vk.fixed.iter().flat_map(|&v| f128(v)).collect::<Vec<u8>>());
    let outer = vk.whir.schedule().expect("a secure configuration");
    let cap0 = cap_size(1 << outer.rounds[0].log_domain, outer.rounds[0].queries);
    let mut mixed = label(b"flock-mixed-v1");
    mixed.extend(bytes_op(&vk.registry_digest));
    mixed.extend(bytes_op(&vk.counts_le));
    mixed.extend(op(5, 0, 32 * cap0 as u64, &[]));
    blob(&mut s, "The statement binding after the public words, up to the commitment's cap.", "BIND_MIXED", &mixed);
    let mut circuit = label(b"flock-circuit-stmt-v2");
    circuit.extend(bytes_op(&vk.circuit_digest));
    circuit.extend(op(5, 0, 32, &[]));
    blob(&mut s, "The statement binding after the cap, up to the digest of the public words.", "BIND_CIRCUIT", &circuit);
    let chunks: Vec<u8> = vk
        .words
        .iter()
        .enumerate()
        .flat_map(|(c, &(at, len))| [at as u32, (len / crate::wrap::outer::ROW_WORDS) as u32, vk.live(c) as u32].map(u32::to_be_bytes).concat())
        .collect();
    blob(&mut s, "Per chunk, where its published words start in the public segment, its rows and its live rows, four bytes each.", "CHUNKS", &chunks);
    let acc: Vec<u8> = vk.acc.iter().flat_map(|&(at, c, r)| [at as u32, c as u32, r as u32].map(u32::to_be_bytes).concat()).collect();
    blob(&mut s, "Per accumulated block claim, its offset in the public segment, its column and its row variables, four bytes each.", "ACC", &acc);
    let bools: Vec<u8> = vk
        .bools
        .iter()
        .flat_map(|t| {
            let mut r = vec![t.k_log as u8, t.prefix as u8, t.table as u8, t.pin.is_some() as u8];
            r.extend_from_slice(&(t.pin.unwrap_or(0) as u32).to_be_bytes());
            r.extend_from_slice(&(t.count as u32).to_be_bytes());
            r
        })
        .collect();
    blob(&mut s, "Per Boolean table type: log size, prefix, committed table, whether a column is pinned, the column and the declared rows (four bytes each).", "BOOLS", &bools);
    let mut data = Vec::new();
    let mut elems = Vec::new();
    for t in &vk.elems {
        elems.extend_from_slice(&[t.kappa as u8, t.prefix as u8]);
        for part in [sparse(&t.a), sparse(&t.b), sparse_vector(&t.a_const), sparse_vector(&t.b_const)] {
            elems.extend_from_slice(&(data.len() as u32).to_be_bytes());
            data.extend(part);
        }
    }
    blob(&mut s, "Per element table type: log columns, prefix, and where its two matrices and two constant vectors start in `ELEM_DATA` (four bytes each).", "ELEMS", &elems);
    blob(&mut s, "The element table types' matrices and constant vectors.", "ELEM_DATA", &data);
    let run_of = |col: usize| vk.runs.iter().position(|r| (r.start..r.start + r.len).contains(&col)).expect("a run") as u16;
    blob(&mut s, "Per gate cell slot, the layout run of the column it reads, two bytes each.", "GATE_RUNS", &vk.gate_cols.iter().flat_map(|&c| run_of(c).to_be_bytes()).collect::<Vec<u8>>());
    let runs: Vec<u8> = vk
        .runs
        .iter()
        .flat_map(|r| {
            let mut o = (r.t0 as u32).to_be_bytes().to_vec();
            o.extend_from_slice(&(r.t1 as u32).to_be_bytes());
            o.extend_from_slice(&(r.start as u16).to_be_bytes());
            o.extend_from_slice(&(r.len as u16).to_be_bytes());
            o
        })
        .collect();
    blob(&mut s, "Per layout run: the cumulative heights before and after a column (four bytes each), its first column and its length (two bytes each).", "RUNS", &runs);

    let (rounds, final_vars) = schedule(&vk.whir);
    blob(&mut s, "The outer commitment's schedule: per function its variables, folded variables, log domain, queries (two bytes), out-of-domain samples and log cap.", "OUTER_ROUNDS", &rounds);
    constant(&mut s, "Variables of the outer commitment's final polynomial.", "OUTER_FINAL", final_vars);
    constant(&mut s, "Proof-of-work bits before the outer commitment's queries.", "OUTER_POW", vk.whir.pow_bits as usize);
    let mut start = label(b"flock-whir-v1");
    start.extend(bytes_op(&vk.whir.to_bytes()));
    start.extend(op(5, 0, 32 * cap0 as u64, &[]));
    blob(&mut s, "The outer opening's transcript up to the cap.", "OUTER_START", &start);

    let layout = &vk.structure.layout;
    constant(&mut s, "log2 of the committed bytes.", "STRUCT_N", layout.n);
    constant(&mut s, "log2 of the block's width in bits.", "K_LOG", layout.k_log);
    constant(&mut s, "The block's sub-blocks before the first Keccak-f one.", "HEAD_SUBS", layout.head_subs);
    constant(&mut s, "The block's Keccak-f sub-blocks.", "KECCAK_SUBS", layout.keccak_subs);
    constant(&mut s, "Bits of a small entry's identifier.", "SMALL_ID", layout.small_id);
    constant(&mut s, "Bits of a small entry's row and of its column.", "SMALL_INDEX", layout.small_index);
    let region = |r: pofseed_flock_lift_structure::key::Region| -> Vec<u8> {
        let mut o = (r.offset as u32).to_be_bytes().to_vec();
        o.push(r.log as u8);
        o
    };
    let mut tables = Vec::new();
    for &(k, held) in &layout.tables {
        tables.push(k as u8);
        match held {
            Held::Dense(regions) => {
                tables.push(0);
                tables.extend(region(regions[0]));
                tables.extend(region(regions[1]));
            }
            Held::Small(id) => {
                tables.push(1);
                tables.extend_from_slice(&[id as u8, 0, 0, 0, 0, 0, 0, 0, 0, 0]);
            }
        }
    }
    blob(&mut s, "Per committed table: its log size, whether it is held as small entries, then its two regions (offset in four bytes, log size) or its identifier.", "TABLES", &tables);
    let regions: Vec<u8> = [layout.ops, layout.masks, layout.kernel, layout.cells, layout.small].into_iter().flat_map(region).collect();
    blob(&mut s, "The regions of the operations, their masks, the Keccak tensor, the cells and the small entries: offset in four bytes, log size.", "REGIONS", &regions);
    let (rounds, final_vars) = schedule(&vk.structure.config);
    blob(&mut s, "The tables' commitment's schedule, laid out as the outer one's.", "STRUCT_ROUNDS", &rounds);
    constant(&mut s, "Variables of the tables' commitment's final polynomial.", "STRUCT_FINAL", final_vars);
    constant(&mut s, "Proof-of-work bits before the tables' commitment's queries.", "STRUCT_POW", vk.structure.config.pow_bits as usize);
    let cap = &vk.structure.commitment.cap;
    let mut start = label(b"flock-whir-v1");
    start.extend(bytes_op(&vk.structure.config.to_bytes()));
    start.extend(bytes_op(cap.as_flattened()));
    blob(&mut s, "The tables' opening's transcript through the cap.", "STRUCT_START", &start);
    blob(&mut s, "The cap of the commitment to the fixed tables.", "STRUCT_CAP", cap.as_flattened());

    label_words(&mut s, "L_STRUCTURE", b"pofseed-flock-lift-structure-v1");
    label_words(&mut s, "L_FOLD", b"flock-matrix-fold-v0");
    let (_, d) = frobenius_constants();
    writeln!(s, "    /// `(x^6 + 1)^-1`.\n    uint256 internal constant D0 = 0x{};", hex::encode(f128(d[0]))).unwrap();
    blob(&mut s, "`δ_i^(2^j)` at `8·i + j` for the basis of GF(2^8) dual to the bits', sixteen bytes each.", "DUAL", &dual().iter().flatten().flat_map(|&v| f128(v)).collect::<Vec<u8>>());
    let domain = Domain::new(32);
    let table = domain.table();
    let mut sub = Vec::new();
    for i in 0..24 {
        for j in 0..32 {
            sub.extend_from_slice(&f128(if j >= i { table[i][j - i] } else { F128::ZERO }));
        }
    }
    blob(&mut s, "The normalised subspace polynomial `Ŵ_i` at `x^j`, at `32·i + j` for `i` in `0..24`, sixteen bytes each.", "SUBSPACE", &sub);
    s.push_str("}\n");
    return s;
}
